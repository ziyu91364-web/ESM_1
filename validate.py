#!/usr/bin/env python3
"""Numerically audit the stationary-resetting manuscript (Python 3 + NumPy).

Install the only dependency with ``python -m pip install numpy``, then run:

    python validate.py
    python validate.py --output another_report.json --random-per-size 500

The default audit uses seed 702319 and up to 2,500 candidate chains at each
size 3,...,8. Reducible candidates are excluded. Checks cover exact three-state
formulas, a reversible isospectral comparator, Fourier formulas for rings,
finite-time variance, congruences, inertia, and threshold bounds. A failure
raises AssertionError and exits unsuccessfully; these numerical checks do not
replace the analytical proofs. Figures are generated by reproduce_figures.py.

The report defaults to validation_results.json beside this script. No network,
SciPy, external data, or machine-specific paths are used.
"""

import argparse
import json
from pathlib import Path

import numpy as np


def sym(matrix):
    return (matrix + matrix.T) / 2


def relative_error(actual, expected):
    return float(np.max(np.abs(actual - expected)) / (1 + np.max(np.abs(expected))))


def require_close(actual, expected, message, tolerance=2e-9):
    error = relative_error(np.asarray(actual), np.asarray(expected))
    assert error <= tolerance, (message, error)
    return error


def representation(rates):
    """Construct the row generator and independent Euclidean centered basis."""
    n = len(rates)
    generator = np.asarray(rates, dtype=float).copy()
    np.fill_diagonal(generator, 0)
    generator -= np.diag(generator.sum(axis=1))
    system = generator.T.copy()
    system[-1, :] = 1
    rhs = np.zeros(n)
    rhs[-1] = 1
    pi = np.linalg.solve(system, rhs)
    if np.min(pi) <= 0:
        raise np.linalg.LinAlgError("Stationary distribution is not positive.")
    root = np.sqrt(pi)
    _, _, vh = np.linalg.svd(root.reshape(1, -1), full_matrices=True)
    basis = vh[1:, :].T
    full = -(root[:, None] * generator) / root[None, :]
    matrix = basis.T @ full @ basis
    symmetric = sym(matrix)
    antisymmetric = (matrix - matrix.T) / 2
    return generator, pi, basis, matrix, symmetric, antisymmetric


def comparison_matrix(symmetric, antisymmetric, r=0., s=None):
    if s is None:
        s = r
    identity = np.eye(len(symmetric))
    return ((symmetric + r * identity) @ (symmetric + s * identity)
            - antisymmetric.T @ antisymmetric)


def local_threshold(symmetric, antisymmetric):
    if np.linalg.eigvalsh(comparison_matrix(symmetric, antisymmetric))[0] >= -1e-12:
        return 0.
    low, high = 0., 1.
    while np.linalg.eigvalsh(comparison_matrix(symmetric, antisymmetric, high))[0] < 0:
        high *= 2
    for _ in range(70):
        mid = (low + high) / 2
        if np.linalg.eigvalsh(comparison_matrix(symmetric, antisymmetric, mid))[0] < 0:
            low = mid
        else:
            high = mid
    return (low + high) / 2


def recovery_threshold(symmetric, antisymmetric):
    values, vectors = np.linalg.eigh(symmetric)
    inverse_root = (vectors * values ** -.5) @ vectors.T
    return max(0., float(np.linalg.eigvalsh(
        inverse_root @ (antisymmetric.T @ antisymmetric) @ inverse_root - symmetric)[-1]))


def inertia(matrix):
    values = np.linalg.eigvalsh(sym(matrix))
    tolerance = 1e-11 * max(float(np.max(np.abs(values))), np.finfo(float).tiny)
    return (int(np.sum(values < -tolerance)), int(np.sum(np.abs(values) <= tolerance)),
            int(np.sum(values > tolerance)))


def exponential(matrix):
    """NumPy-only matrix exponential: scaled Taylor series followed by squaring."""
    size = np.linalg.norm(matrix, ord=np.inf)
    scaling = max(0, int(np.ceil(np.log2(max(1., 2 * size)))))
    reduced = matrix / (2. ** scaling)
    result = np.eye(len(matrix))
    term = result.copy()
    for k in range(1, 101):
        term = term @ reduced / k
        result += term
        if np.linalg.norm(term, ord=np.inf) < 2e-17:
            break
    else:
        raise AssertionError("Matrix-exponential series did not converge.")
    for _ in range(scaling):
        result = result @ result
    return result


def audit_family():
    report = []
    for a in [1., 1.25, 2., 3., 3.999, 4., 4.001, 5., 10., 25., 100., 10000.]:
        rates = np.array([[0, a, 0], [0, 0, 1], [1, 0, 0]], dtype=float)
        generator, pi, _, matrix, symmetric, antisymmetric = representation(rates)
        d = 2 * a + 1
        expected_pi = np.array([1, a, a]) / d
        e1 = np.array([2 * a, -1, -1]) / np.sqrt(2 * a)
        e2 = np.array([0, 1, -1]) * np.sqrt(d / (2 * a))
        basis = np.stack([e1, e2], axis=1)
        expected = np.array([[a + .5, -np.sqrt(d) / 2], [np.sqrt(d) / 2, 1.5]])
        error = require_close(pi, expected_pi, "Three-state stationary law")
        error = max(error, require_close(pi @ generator, np.zeros(3), "Stationarity"))
        error = max(error, require_close(basis.T @ np.diag(pi) @ basis, np.eye(2), "Orthonormality"))
        error = max(error, require_close(pi @ basis, np.zeros(2), "Centering"))
        error = max(error, require_close(basis.T @ np.diag(pi) @ (-generator) @ basis,
                                         expected, "Three-state reduced generator"))
        rlocal = local_threshold(symmetric, antisymmetric)
        rrecovery = recovery_threshold(symmetric, antisymmetric)
        exact_local = max(0., (np.sqrt(d) - 3) / 2)
        exact_recovery = max(0., (a - 4) / 3)
        error = max(error, require_close(rlocal, exact_local, "Three-state local threshold"))
        error = max(error, require_close(rrecovery, exact_recovery, "Three-state recovery"))
        for r in [0., .01, .1, .5, 1., 3., 10., 100.]:
            reset = generator + r * (np.ones((3, 1)) * pi[None, :] - np.eye(3))
            full_resolvent = np.linalg.inv(-reset + np.ones((3, 1)) * pi[None, :])
            reduced_resolvent = np.linalg.inv(expected + r * np.eye(2))
            denominator = r * r + (a + 2) * r + d
            exact_variances = np.diag([(2 * r + 3) / denominator, (2 * r + d) / denominator])
            exact_derivatives = np.diag([
                (a - 4 - 6 * r - 2 * r * r) / denominator ** 2,
                (-2 * r * r - 2 * d * r - a * d) / denominator ** 2])
            error = max(error, require_close(2 * sym(basis.T @ np.diag(pi) @ full_resolvent @ basis),
                                             exact_variances, "Three-state full variance"))
            error = max(error, require_close(-2 * sym(reduced_resolvent @ reduced_resolvent),
                                             exact_derivatives, "Three-state derivatives"))
        if a > 4:
            lm = (a + 2 - np.sqrt(a * (a - 4))) / 2
            lp = (a + 2 + np.sqrt(a * (a - 4))) / 2
            error = max(error, require_close(np.sort(np.linalg.eigvals(matrix)), [lm, lp], "Real spectrum"))
            reversible_rates = np.array([
                [0, a * lm / d, a * lm / d],
                [lm / d, 0, (d * lp - lm) / (2 * d)],
                [lm / d, (d * lp - lm) / (2 * d), 0]])
            assert np.all(reversible_rates[~np.eye(3, dtype=bool)] > 0)
            reversible = reversible_rates - np.diag(reversible_rates.sum(axis=1))
            flux = np.diag(pi) @ reversible
            error = max(error, require_close(flux, flux.T, "Comparator detailed balance"))
            error = max(error, require_close(basis.T @ np.diag(pi) @ (-reversible) @ basis,
                                             np.diag([lm, lp]), "Isospectral comparator"))
            weights = np.array([(1.5 - lm) / (lp - lm), (lp - 1.5) / (lp - lm)])
            assert weights[0] < 0 and weights[1] > 1
            for time in [0., .01, .1, 1., 3.]:
                direct = exponential(-expected * time)[0, 0]
                exact = weights @ np.exp(-np.array([lm, lp]) * time)
                error = max(error, require_close(direct, exact, "Signed covariance"))
            peak = (2 * exact_local + 3) / (exact_local ** 2 + (a + 2) * exact_local + d)
            error = max(error, require_close(peak / (3 / d),
                                             2 * d / (3 * (a - 1 + np.sqrt(d))), "Peak amplification"))
        assert error < 2e-9
        report.append(dict(a=a, local_threshold=rlocal, recovery_threshold=rrecovery,
                           maximum_relative_error=error))
    return report


def audit_rings():
    rng = np.random.default_rng(126893)
    cases = 0
    maximum_error = 0.
    for n in range(3, 16):
        for p, q in [(1., 0.), (0., 1.), (1., 1.), (1., .2), (.4, 2.)]:
            rates = np.zeros((n, n))
            for j in range(n):
                rates[j, (j + 1) % n] = p
                rates[j, (j - 1) % n] = q
            generator, pi, _, _, symmetric, antisymmetric = representation(rates)
            theta = 2 * np.pi * np.arange(1, n) / n
            lambdas = (p + q) * (1 - np.cos(theta))
            omegas = (p - q) * np.sin(theta)
            f = rng.normal(size=n)
            f -= f.mean()
            transform = np.fft.fft(f)[1:] / n
            expected_local = max(0., float(np.max(np.abs(omegas) - lambdas)))
            expected_recovery = max(0., float(np.max(omegas ** 2 / lambdas - lambdas)))
            maximum_error = max(maximum_error, require_close(local_threshold(symmetric, antisymmetric),
                                                              expected_local, "Ring local threshold"))
            maximum_error = max(maximum_error, require_close(recovery_threshold(symmetric, antisymmetric),
                                                              expected_recovery, "Ring recovery threshold"))
            strict_onset = abs(p - q) / (p + q) > np.tan(np.pi / n) + 1e-12
            assert (expected_local > 1e-12) == strict_onset
            for r in [0., .1, 1., 10.]:
                reset = generator + r * (np.ones((n, 1)) * pi[None, :] - np.eye(n))
                direct = 2 * np.dot(pi * f, np.linalg.solve(-reset + np.ones((n, 1)) * pi[None, :], f))
                exact = 2 * np.sum(np.abs(transform) ** 2 * (lambdas + r)
                                   / ((lambdas + r) ** 2 + omegas ** 2))
                maximum_error = max(maximum_error, require_close(direct, exact, "Fourier variance"))
                cases += 1
    return dict(variance_comparisons=cases, generator_parameter_sets=65,
                maximum_relative_error=maximum_error)


def audit_finite_time():
    rng = np.random.default_rng(491274)
    maximum_ratio = 0.
    maximum_exponential_error = 0.
    cases = 0
    # Symmetric examples check the exponential independently by the spectral theorem.
    for n in range(2, 9):
        rates = rng.uniform(.05, 2, (n, n))
        rates = (rates + rates.T) / 2
        _, _, _, matrix, _, _ = representation(rates)
        values, vectors = np.linalg.eigh(matrix)
        for time in [.01, .1, 1.]:
            exact = (vectors * np.exp(-values * time)) @ vectors.T
            maximum_exponential_error = max(maximum_exponential_error,
                require_close(exponential(-matrix * time), exact, "Exponential spectral check"))
    for n in range(2, 9):
        for iteration in range(10):
            rates = 10 ** rng.uniform(-1, 1, (n, n))
            _, _, _, matrix, symmetric, _ = representation(rates)
            gamma = np.linalg.eigvalsh(symmetric)[0]
            f = rng.normal(size=n - 1)
            for r in [0., .3, 2.]:
                reset_matrix = matrix + r * np.eye(n - 1)
                resolvent = np.linalg.inv(reset_matrix)
                for dimensionless_time in [.01, .1, 1., 5.]:
                    time = dimensionless_time / (gamma + r)
                    exp_matrix = exponential(-reset_matrix * time)
                    integrated = resolvent - resolvent @ resolvent @ (np.eye(n - 1) - exp_matrix) / time
                    finite = 2 * f @ integrated @ f
                    asymptotic = 2 * f @ resolvent @ f
                    bound = 2 * (f @ f) * (-np.expm1(-(gamma + r) * time)) / (time * (gamma + r) ** 2)
                    deviation = abs(finite - asymptotic)
                    assert finite >= -1e-10
                    assert deviation <= bound * (1 + 1e-9) + 1e-10
                    maximum_ratio = max(maximum_ratio, float(deviation / bound))
                    cases += 1
    return dict(finite_time_comparisons=cases, maximum_deviation_to_bound_ratio=maximum_ratio,
                maximum_exponential_relative_error=maximum_exponential_error)


def audit_random(seed, candidates_per_size):
    rng = np.random.default_rng(seed)
    cases = positive_cases = inertia_checks = sign_checks = 0
    max_finite = max_derivative = max_full = 0.
    min_gap = float("inf")
    min_lower_slack = min_upper_slack = float("inf")
    for n in range(3, 9):
        for iteration in range(candidates_per_size):
            rates = 10 ** rng.uniform(-1, 1, (n, n))
            np.fill_diagonal(rates, 0)
            if iteration < min(1000, candidates_per_size * 2 // 5):
                rates = rng.integers(0, 11, (n, n)).astype(float)
                np.fill_diagonal(rates, 0)
            if iteration >= min(1500, candidates_per_size * 3 // 5):
                rates = .02 * rng.random((n, n))
                np.fill_diagonal(rates, 0)
                for i in range(n):
                    rates[i, (i + 1) % n] = 10 ** rng.uniform(-1, 1)
            if (rates.sum(0) == 0).any() or (rates.sum(1) == 0).any():
                continue
            try:
                generator, pi, basis, matrix, symmetric, antisymmetric = representation(rates)
            except np.linalg.LinAlgError:
                continue
            svalues = np.linalg.eigvalsh(symmetric)
            if svalues[0] < 1e-9:
                continue
            cases += 1
            r, s = sorted(rng.uniform(0, 3, 2))
            identity = np.eye(n - 1)
            first = matrix + r * identity
            second = matrix + s * identity
            first_inverse = np.linalg.inv(first)
            second_inverse = np.linalg.inv(second)
            product_inverse = np.linalg.inv(first @ second)
            qfinite = comparison_matrix(symmetric, antisymmetric, r, s)
            finite = sym((first_inverse - second_inverse) / (s - r))
            finite_congruence = product_inverse.T @ qfinite @ product_inverse
            max_finite = max(max_finite, float(np.max(np.abs(finite - finite_congruence))))
            require_close(finite, finite_congruence, "Finite comparison congruence")
            inverse_squared = first_inverse @ first_inverse
            qlocal = comparison_matrix(symmetric, antisymmetric, r)
            derivative_congruence = inverse_squared.T @ qlocal @ inverse_squared
            max_derivative = max(max_derivative, float(np.max(np.abs(sym(inverse_squared) - derivative_congruence))))
            require_close(sym(inverse_squared), derivative_congruence, "Derivative congruence")
            assert inertia(finite) == inertia(qfinite), ("Finite inertia", n, r, s)
            assert inertia(sym(inverse_squared)) == inertia(qlocal), ("Derivative inertia", n, r)
            inertia_checks += 2
            u = rng.normal(size=n - 1)
            f = basis @ u / np.sqrt(pi)
            reset_generator = generator + r * (np.ones((n, 1)) * pi[None, :] - np.eye(n))
            full_resolvent = np.linalg.inv(-reset_generator + np.ones((n, 1)) * pi[None, :])
            full_variance = 2 * np.dot(pi * f, full_resolvent @ f)
            reduced_variance = 2 * u @ first_inverse @ u
            max_full = max(max_full, abs(float(full_variance - reduced_variance)))
            require_close(full_variance, reduced_variance, "Full and reduced variance")
            rlocal = local_threshold(symmetric, antisymmetric)
            rrecovery = recovery_threshold(symmetric, antisymmetric)
            anorm = np.linalg.norm(antisymmetric, 2)
            assert max(0., anorm - svalues[-1]) <= rlocal + 1e-8
            assert rlocal <= max(0., anorm - svalues[0]) + 1e-8
            if rlocal > 1e-10:
                positive_cases += 1
                gap = rrecovery - 2 * rlocal
                min_gap = min(min_gap, gap)
                assert gap > 0
                lower_slack = rrecovery - (2 * rlocal + rlocal ** 2 / svalues[-1])
                upper_slack = 2 * rlocal + rlocal ** 2 / svalues[0] - rrecovery
                min_lower_slack = min(min_lower_slack, lower_slack)
                min_upper_slack = min(min_upper_slack, upper_slack)
                assert lower_slack >= -1e-8 and upper_slack >= -1e-8
                for fraction in [.8, 1.2]:
                    inverse = np.linalg.inv(matrix + fraction * rlocal * identity)
                    direct = -2 * sym(inverse @ inverse)
                    assert (np.linalg.eigvalsh(direct)[-1] > 0) == (fraction < 1)
                    sign_checks += 1
                for fraction in [.8, 1.2]:
                    difference = sym(np.linalg.inv(matrix) - np.linalg.inv(matrix + fraction * rrecovery * identity))
                    assert (np.linalg.eigvalsh(difference)[0] < 0) == (fraction < 1)
                    sign_checks += 1
            else:
                assert rrecovery < 1e-8
    return dict(seed=seed, candidates_per_size=candidates_per_size, state_sizes=list(range(3, 9)),
                accepted_irreducible_chains=cases, positive_threshold_chains=positive_cases,
                inertia_comparisons=inertia_checks, direct_threshold_sign_checks=sign_checks,
                sign_mismatches=0, maximum_finite_congruence_absolute_error=max_finite,
                maximum_derivative_congruence_absolute_error=max_derivative,
                maximum_full_variance_absolute_error=max_full,
                minimum_strict_recovery_gap=None if positive_cases == 0 else min_gap,
                minimum_recovery_lower_bound_slack=None if positive_cases == 0 else min_lower_slack,
                minimum_recovery_upper_bound_slack=None if positive_cases == 0 else min_upper_slack)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().with_name("validation_results.json"))
    parser.add_argument("--seed", type=int, default=702319)
    parser.add_argument("--random-per-size", type=int, default=2500)
    arguments = parser.parse_args()
    if arguments.random_per_size < 1:
        parser.error("--random-per-size must be positive")
    report = dict(status="passed", numpy_version=np.__version__,
                  three_state_family=audit_family(), rings=audit_rings(),
                  finite_time=audit_finite_time(), random_chains=audit_random(arguments.seed, arguments.random_per_size),
                  interpretation="Numerical consistency checks; the analytical proofs establish the general claims.")
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    print("All checks passed. Report:", arguments.output)


if __name__ == "__main__":
    main()
